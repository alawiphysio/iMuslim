data class HDate(val year: Int, val month: Int, val day: Int)   // month: 0..11

/** المواسم: كل موسم له شكل ورسالة خاصة */
enum class Season(
    val title: String,
    val skyTop: Int, val skyBottom: Int,
    val tag: String
) {
    NORMAL("", 0xFF061512.toInt(), 0xFF0E3A30.toInt(), ""),
    FRIDAY("جمعة مباركة", 0xFF0B1A10.toInt(), 0xFF3A3A12.toInt(), "🕌 جمعة مباركة"),
    RAMADAN("رمضان كريم", 0xFF0D0820.toInt(), 0xFF2B1B52.toInt(), "🌙 رمضان كريم"),
    EID_FITR("عيد فطر مبارك", 0xFF06222E.toInt(), 0xFF1D6B6B.toInt(), "🎉 عيد مبارك"),
    DHUL_HIJJAH("عشر ذي الحجة", 0xFF1A1206.toInt(), 0xFF4A3410.toInt(), "🕋 عشر ذي الحجة"),
    ARAFAH("يوم عرفة", 0xFF1E0F04.toInt(), 0xFF6B3E12.toInt(), "🤲 يوم عرفة"),
    EID_ADHA("عيد أضحى مبارك", 0xFF06222E.toInt(), 0xFF1D6B6B.toInt(), "🎉 عيد مبارك");

    val festive get() = this == EID_FITR || this == EID_ADHA

    companion object {
        fun current(now: Long = System.currentTimeMillis()): Season {
            val h = Hijri.date(now)
            val c = Calendar.getInstance(); c.timeInMillis = now
            return when {
                h.month == IslamicCalendar.SHAWWAL && h.day <= 3 -> EID_FITR
                h.month == IslamicCalendar.DHU_AL_HIJJAH && h.day in 10..13 -> EID_ADHA
                h.month == IslamicCalendar.DHU_AL_HIJJAH && h.day == 9 -> ARAFAH
                h.month == IslamicCalendar.DHU_AL_HIJJAH && h.day <= 8 -> DHUL_HIJJAH
                h.month == IslamicCalendar.RAMADAN -> RAMADAN
                c.get(Calendar.DAY_OF_WEEK) == Calendar.FRIDAY -> FRIDAY
                else -> NORMAL
            }
        }
    }
}

